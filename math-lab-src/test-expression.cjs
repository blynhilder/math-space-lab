'use strict';
const assert = require('node:assert/strict');
const { compile, limits } = require('./expression.js');
const value = (source, vars = {}) => compile(source).evaluate({ x: 2, y: 3, a: 0.5, b: -0.5, ...vars });
const close = (actual, expected) => assert.ok(Math.abs(actual - expected) < 1e-10, actual + ' ≠ ' + expected);
close(value('a*x^2+b*y**2'), -2.5);
close(value('sin(pi/2)+cos(0)+tan(pi/4)'), 3);
close(value('sqrt(x^2+y^2)'), Math.sqrt(13));
close(value('exp(ln(e)) + abs(-3)'), Math.E + 3);
close(value('log(e)+log10(100)'), 3);
close(value('min(x,y)+max(a,b)+atan2(0,-1)'), 2.5 + Math.PI);
close(value('cbrt(-8)+asin(1)+acos(1)+atan(0)'), -2 + Math.PI/2);
close(value('1e-3 + 2.5E+2 + .5'), 250.501);
close(value('-x^2'), -4);
close(value('(-x)^2'), 4);
close(value('2^3^2'), 512);
close(value('2^-2'), 0.25);
close(value('-2^-2'), -0.25);
close(value('8/4/2'), 1);
close(value('10-3-2'), 5);
for (const source of ['sqrt(-1)','log(0)','ln(-2)','1/0','0/0','exp(1000)','(-1)^0.5','tan(pi/2)','0*sqrt(-1)','sqrt(-1)^0']) assert.ok(Number.isNaN(value(source)), source);
for (const source of ['', 'x+', '2x', 'sin x', 'sin()', 'sin(x,y)', 'max(x)', 'x=2', 'z=x+y', 'x;y', 'alert(1)', 'Math.sin(x)', 'x.constructor', '__proto__', 'constructor(x)', '[1,2]', 'window', 'process.exit()', 'x ? 1 : 0', '1e999', 'x)']) assert.throws(() => compile(source), undefined, source);
assert.throws(() => compile('x'.repeat(limits.length + 1)));
assert.throws(() => compile('('.repeat(26)+'x'+')'.repeat(26)));
assert.throws(() => compile(Array.from({length:100},()=> 'x').join('+')));
assert.ok(Number.isNaN(compile('x').evaluate({})));
assert.ok(Number.isNaN(compile('x').evaluate(Object.create({x:2}))));
console.log('Expression checks passed: precedence, functions, real domains, zero division, malicious syntax, complexity limits.');
